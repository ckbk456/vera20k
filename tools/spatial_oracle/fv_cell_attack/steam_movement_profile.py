def generate():
    """Execute existing native owners; no Rust output initializes native state."""
    import json
    from pathlib import Path
    from tools.spatial_oracle import track_speed_native, track_destination, track_outer_continuation
    profile = STEAM_NUMERIC_PROFILE
    numeric = track_speed_native.generate(profile=profile)
    historical = json.loads(Path(track_speed_native.__file__).with_suffix('.json').read_text())
    assert numeric == historical, 'The original numeric bodies no longer reproduce the historical payload'
    changes = (
        ('rest', {}), ('destination', {'destination': (2688, 2688, 208)}),
        ('head', {'head': (2688, 2688, 208)}), ('path0', {'path_head': 0}),
        ('path8', {'path_head': 8}), ('zero', {'applied': 0.0}),
        ('negative_zero', {'applied': -0.0}), ('stop_value', {'applied': 0.30000001192092896}),
        ('full', {'applied': 1.0}), ('destination_z', {'destination': (0, 0, 1)}),
        ('head_y', {'head': (0, 1, 0)}), ('frame100', {'frame': 100}),
    )
    tails = []
    for family in ('drive', 'ship'):
        for name, change in changes:
            case = dict(name=family + '_' + name, family=family, raw=25, applied=.2, target=.75)
            case.update(change)
            tails.append(track_outer_continuation.rest_tail(case, profile=profile))
    callers, ship_callers = [], []
    for name, change in (
        ('guard_settled', {}), ('guard_turning', {'rotating': True}),
        ('retained_selector', {'selector': 27}), ('ordinary_no_moving_no_path', {'mission': 0}),
        ('unload', {'mission': 16}), ('rotating_destination', {'rotating': True, 'destination': (2688, 2688, 208)}),
        ('rotating_head', {'rotating': True, 'head': (2688, 2688, 208)}),
        ('rotating_path', {'rotating': True, 'path_head': 0}),
    ):
        case = dict(name=name, caller_entry=True, raw=25, applied=.2, target=.75)
        case.update(change)
        callers.append(track_outer_continuation.rest_tail(case, profile=profile))
        ship_case = dict(case, family='ship', name='ship_' + name)
        ship_callers.append(track_outer_continuation.rest_tail(ship_case, profile=profile))
    stops = [track_destination.stop_speed_owner(
        dict(name=f'{family}_target_{target}', family=family, raw=25, applied=applied, target=target), profile=profile)
        for family in ('drive', 'ship') for target in (0., .2, .30000001192092896, .75, 1.) for applied in (.2, 1.)]
    high = [track_speed_native.getter(dict(raw=255, house=16., crate=2., applied=fraction), profile=profile)
            for fraction in (0., .2, .30000001192092896, 1.)]
    return dict(schema_version=1, numeric=numeric, stops=stops, tails=tails, callers=callers, ship_callers=ship_callers,
                high_integer_getters=high,
                excluded=['Full FV/Scenario/Windows startup and effective retail INI producers',
                          'Active paid-point/fresh/arrival/Stop Event/Move resume histories',
                          'Process early bypass returns and land-effect Anim allocation'])


